"""멀리 있는 바닥과 하늘 경계만 부드럽게 연결한다. 전투 영역에는 안개를 넣지 않는다."""
import unreal
le=unreal.get_editor_subsystem(unreal.LevelEditorSubsystem)
eas=unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
actors=eas.get_all_level_actors()
fog=next((a for a in actors if isinstance(a,unreal.ExponentialHeightFog)),None)
if fog is None:fog=eas.spawn_actor_from_class(unreal.ExponentialHeightFog,unreal.Vector(0,0,0))
fog.set_actor_label('Comic Horizon Haze')
fog.set_actor_hidden_in_game(False)
fog.set_is_temporarily_hidden_in_editor(False)
fog.set_actor_location(unreal.Vector(0,0,0),False,False)
c=fog.get_component_by_class(unreal.ExponentialHeightFogComponent)
c.set_visibility(True)
c.set_hidden_in_game(False)
c.set_fog_density(.006)
c.set_fog_height_falloff(.16)
c.set_start_distance(1800)
c.set_fog_max_opacity(.78)
c.set_fog_inscattering_color(unreal.LinearColor(.035,.018,.065,1))
c.set_editor_property('enable_volumetric_fog',False)
le.save_current_level()
print('CC3_HORIZON_HAZE_SAVED')
